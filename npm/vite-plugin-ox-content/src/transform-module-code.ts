import type { TransformResult } from "./types";

type ModuleContent = Omit<TransformResult, "code">;

// Snapshot mutable metadata while the transform completes, even when the host
// only needs HTML. Later callback mutations must not change generated modules.
function snapshotModuleFields(input: ModuleContent) {
  return {
    frontmatterJson: JSON.stringify(input.frontmatter),
    tocJson: JSON.stringify(input.toc),
    importsJson: JSON.stringify(input.imports),
    exportsJson: JSON.stringify(input.exports),
    componentsJson: JSON.stringify(input.components),
    crossReferencesJson: JSON.stringify(input.crossReferences),
    citationsJson: JSON.stringify(input.citations),
    bibliographyJson: JSON.stringify(input.bibliography),
  };
}

export function attachModuleCode(
  result: TransformResult,
  filePath: string,
  deferModuleCode = false,
): TransformResult {
  const fields = snapshotModuleFields(result);
  const html = result.html;
  if (!deferModuleCode) {
    result.code = generateModuleCode(html, filePath, fields);
    return result;
  }

  let code = "";
  let generated = false;
  Object.defineProperty(result, "code", {
    enumerable: true,
    configurable: true,
    get() {
      if (!generated) {
        code = generateModuleCode(html, filePath, fields);
        generated = true;
      }
      return code;
    },
    set(value: string) {
      code = value;
      generated = true;
    },
  });
  return result;
}

function generateModuleCode(
  html: string,
  filePath: string,
  fields: ReturnType<typeof snapshotModuleFields>,
): string {
  const htmlJson = JSON.stringify(html);
  const {
    frontmatterJson,
    tocJson,
    importsJson,
    exportsJson,
    componentsJson,
    crossReferencesJson,
    citationsJson,
    bibliographyJson,
  } = fields;
  return `
// Generated by @ox-content/vite-plugin
// Source: ${filePath}

/**
 * Rendered HTML content.
 */
export const html = ${htmlJson};

/**
 * Parsed frontmatter.
 */
export const frontmatter = ${frontmatterJson};

/**
 * Table of contents.
 */
export const toc = ${tocJson};

/**
 * MDX import statements collected from the AST.
 */
export const imports = ${importsJson};

/**
 * MDX export names collected from the AST.
 */
export const exports = ${exportsJson};

/**
 * Unique JSX component names collected from the AST.
 */
export const components = ${componentsJson};

/**
 * Labeled cross-reference targets collected from this document.
 */
export const crossReferences = ${crossReferencesJson};

/**
 * Citation references collected from this document.
 */
export const citations = ${citationsJson};

/**
 * Bibliography entries used by this document.
 */
export const bibliography = ${bibliographyJson};

/**
 * Default export with all data.
 */
export default {
  html,
  frontmatter,
  toc,
  imports,
  exports,
  components,
  crossReferences,
  citations,
  bibliography,
};

// HMR support
if (import.meta.hot) {
  import.meta.hot.accept((newModule) => {
    if (newModule) {
      // Trigger re-render with new content
      import.meta.hot.invalidate();
    }
  });
}
`;
}
